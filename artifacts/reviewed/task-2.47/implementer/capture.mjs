import { chromium } from '/mnt/d/Source/QOpenBB/verification/node_modules/@playwright/test/index.mjs';
import fs from 'node:fs';
const dir='/mnt/d/Source/QOpenBB/artifacts/task-2.47/implementer';
const env={...process.env}; delete env.WAYLAND_DISPLAY;
const browser=await chromium.launch({headless:true,env,args:['--ozone-platform=headless','--use-gl=angle','--use-angle=swiftshader-webgl','--enable-unsafe-swiftshader']});
try {
  const context=await browser.newContext({viewport:{width:1000,height:550}});
  const page=await context.newPage();
  const errors=[];
  page.on('pageerror',e=>{errors.push(e.message);console.log(e.message);});
  page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
  const cdp=await context.newCDPSession(page);
  await cdp.send('Runtime.enable'); await cdp.send('Network.enable');
  await page.goto('http://127.0.0.1:6017/',{waitUntil:'domcontentloaded',timeout:20000});
  await page.getByRole('button',{name:'Grouped Column. Selected',exact:true}).first().waitFor();
  await page.screenshot({path:dir+'/gallery-light-dark.png'});
  const gallery=page.getByRole('region',{name:'Chart types'}).first();
  await gallery.evaluate(el=>el.scrollTop=300);
  const line=gallery.getByRole('button',{name:'Line',exact:true});
  await line.focus();
  const before=await gallery.evaluate(el=>el.scrollTop);
  await page.keyboard.press('Enter');
  await page.getByRole('button',{name:'Line. Selected',exact:true}).first().waitFor();
  if(await gallery.evaluate(el=>el.scrollTop)!==before) throw Error('selection reset scroll');
  await page.keyboard.press('Space');
  if(await page.locator('output').first().textContent()!=='line') throw Error('keyboard callback failed');
  await page.screenshot({path:dir+'/gallery-keyboard-selection.png'});
  fs.writeFileSync(dir+'/browser-results.json',JSON.stringify({errors,keyboard:'Enter and Space',scrollBefore:before,scrollAfter:await gallery.evaluate(el=>el.scrollTop),buttonCount:await gallery.getByRole('button').count()},null,2));
  if(errors.length) throw Error(JSON.stringify(errors));
} finally { await browser.close(); }
