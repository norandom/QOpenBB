import { chromium, expect } from '/mnt/d/Source/QOpenBB/verification/node_modules/@playwright/test/index.mjs';
import fs from 'node:fs';
const dir='/mnt/d/Source/QOpenBB/artifacts/task-2.48/implementer';
const env={...process.env}; delete env.WAYLAND_DISPLAY;
const browser=await chromium.launch({headless:true,env,args:['--ozone-platform=headless','--use-gl=angle','--use-angle=swiftshader-webgl','--enable-unsafe-swiftshader']});
try {
  const context=await browser.newContext({viewport:{width:900,height:700}});
  const page=await context.newPage();
  const errors=[]; const networkFailures=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
  page.on('requestfailed',r=>networkFailures.push(r.url()));
  const cdp=await context.newCDPSession(page);
  await cdp.send('Runtime.enable'); await cdp.send('Network.enable');
  await page.goto('http://127.0.0.1:6017/',{waitUntil:'networkidle',timeout:20000});
  const light=page.locator('[data-theme="light"]');
  await light.getByRole('button',{name:'Grouped Column. Selected',exact:true}).waitFor();
  await page.screenshot({path:dir+'/dock-light-dark.png'});
  const gallery=light.getByRole('region',{name:'Chart types'});
  await gallery.getByRole('button',{name:'Grouped Bar',exact:true}).click();
  await expect(light.locator('output')).toHaveText('groupedBar');
  await gallery.evaluate(el=>el.scrollTop=300);
  await light.getByRole('button',{name:'Collapse chart editor'}).evaluate(el=>el.click());
  await expect(light.getByRole('button',{name:'Chart settings'})).toBeFocused();
  await light.getByRole('button',{name:'Chart settings'}).click();
  await expect(light.getByRole('tab',{name:'Chart',exact:true})).toBeFocused();
  if(await gallery.evaluate(el=>el.scrollTop)!==300) throw Error('gallery scroll lost');
  await light.getByRole('tab',{name:'Customize',exact:true}).click();
  await light.getByRole('button',{name:'Customize group'}).click();
  await light.getByRole('textbox').fill('Retained fixture');
  await light.getByRole('tabpanel').evaluate(el=>el.scrollTop=547);
  await light.getByRole('textbox').focus();
  await light.getByRole('button',{name:'Collapse chart editor'}).evaluate(el=>el.click());
  await expect(light.getByRole('button',{name:'Chart settings'})).toBeFocused();
  await light.getByRole('button',{name:'Chart settings'}).click();
  await expect(light.getByRole('tab',{name:'Customize',exact:true})).toBeFocused();
  await expect(light.getByRole('textbox')).toHaveValue('Retained fixture');
  if(await light.getByRole('tabpanel').evaluate(el=>el.scrollTop)!==547) throw Error('Customize scroll lost');
  await light.getByRole('tab',{name:'Set Up',exact:true}).click();
  await expect(light.getByRole('button',{name:'Setup group'})).toBeVisible();
  await light.getByRole('tab',{name:'Customize',exact:true}).click();
  await expect(light.getByRole('textbox')).toHaveCount(0);
  await light.getByRole('button',{name:'Customize group'}).click();
  await light.getByRole('button',{name:'Rebuild fixture theme'}).click();
  await expect(light.getByRole('textbox')).toHaveCount(0);
  await expect(light.getByRole('tab',{name:'Customize',exact:true})).toHaveAttribute('aria-selected','true');
  const width=await light.getByRole('complementary').evaluate(el=>el.getBoundingClientRect().width);
  if(width!==260) throw Error(`dock width ${width}`);
  fs.writeFileSync(dir+'/browser-results.json',JSON.stringify({errors,networkFailures,width,galleryScroll:300,customizeScroll:547,checks:['exact gallery callback','close opener focus','reopen selected tab focus','hide retains fixture state and scroll','Set Up destination','tab departure resets Customize','live theme resets Customize']},null,2));
  if(errors.length || networkFailures.length) throw Error(JSON.stringify({errors,networkFailures}));
} finally { await browser.close(); }

